"""Markdown reports, charts, failure logs and paired run comparison."""

from __future__ import annotations

import glob
import json
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from rag_eval.aggregate import METRICS_BY_KEY, MetricSpec
from rag_eval.loading import load_questions
from rag_eval.schema import EvalQuestion, QuestionResult, RunConfig
from rag_eval.stats import paired_bootstrap
from rag_eval.version import __version__

logger = logging.getLogger(__name__)

MAIN_METRICS = [
    "hit",
    "recall",
    "mrr",
    "groundedness",
    "citation_precision",
    "correctness",
    "refusal_accuracy",
]
DIAGNOSTIC_METRICS = ["precision", "hallucinated_citation_rate", "false_refusal_rate"]
COMPARE_METRICS = MAIN_METRICS + DIAGNOSTIC_METRICS
N_FAILURES = 5
DASH = "–"


class RunLoadError(ValueError):
    """A folder is not a complete run (missing or invalid output files)."""


class CompareError(ValueError):
    """Two runs cannot be compared fairly."""


@dataclass
class LoadedRun:
    path: Path
    config: RunConfig
    results: list[QuestionResult]
    summary: dict[str, Any]

    @property
    def name(self) -> str:
        return self.config.run_id


# --- loading -----------------------------------------------------------------------------


def load_run(path: str | Path) -> LoadedRun:
    folder = Path(path)
    files = {name: folder / name for name in ("config.json", "results.jsonl", "summary.json")}
    missing = [name for name, f in files.items() if not f.is_file()]
    if missing:
        raise RunLoadError(f"{folder} is not a run folder (missing {', '.join(missing)})")
    config = RunConfig.model_validate_json(files["config.json"].read_text(encoding="utf-8"))
    lines = files["results.jsonl"].read_text(encoding="utf-8").splitlines()
    results = [QuestionResult.model_validate_json(line) for line in lines if line.strip()]
    summary = json.loads(files["summary.json"].read_text(encoding="utf-8"))
    return LoadedRun(folder, config, results, summary)


def expand_run_paths(patterns: list[str]) -> list[Path]:
    """Expand globs (PowerShell does not) and keep only folders that contain a run."""
    paths: list[Path] = []
    for pattern in patterns:
        matches = sorted(glob.glob(pattern)) if glob.has_magic(pattern) else [pattern]
        for match in matches:
            path = Path(match)
            if (path / "config.json").is_file():
                paths.append(path)
            elif path.is_dir() or glob.has_magic(pattern):
                logger.info("skipping %s: not a run folder", path)
            else:
                raise RunLoadError(f"{path} is not a run folder")
    return paths


# --- formatting --------------------------------------------------------------------------


def fmt_stat(stat: dict[str, Any] | None, with_n: bool = True) -> str:
    """``0.800 [0.600, 1.000] (n=12)``, or a dash when there is no data."""
    if not stat or stat.get("mean") is None:
        return DASH
    text = f"{stat['mean']:.3f} [{stat['low']:.3f}, {stat['high']:.3f}]"
    return f"{text} (n={stat['n']})" if with_n else text


def _fmt_num(value: float | None, digits: int = 2) -> str:
    return DASH if value is None else f"{value:.{digits}f}"


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def md_table(headers: list[str], rows: list[list[Any]]) -> str:
    lines = [
        "| " + " | ".join(_cell(h) for h in headers) + " |",
        "|" + "|".join("---" for _ in headers) + "|",
    ]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _k_label(runs: list[LoadedRun]) -> int | str:
    ks = {r.config.k for r in runs}
    return ks.pop() if len(ks) == 1 else "k"


def _has_data(runs: list[LoadedRun], key: str) -> bool:
    return any(r.summary["overall"][key]["n"] for r in runs)


def _short(sha: str) -> str:
    return sha[:12]


# --- report ------------------------------------------------------------------------------


def _header(runs: list[LoadedRun]) -> list[str]:
    rows = [
        [
            r.name,
            r.config.system,
            r.config.k,
            r.summary["n_questions"],
            r.summary["n_errors"],
            f"`{_short(r.config.questions_sha256)}`",
            r.config.judge_model or "none (retrieval only)",
            r.config.rag_eval_version,
            r.config.created_at,
        ]
        for r in runs
    ]
    headers = ["Run", "System", "k", "Questions", "Errors", "Questions sha256", "Judge model"]
    headers += ["rag-eval", "Created (UTC)"]
    out = [
        "# rag-eval report",
        "",
        f"Generated by rag-eval {__version__}. Every metric is shown as "
        "`mean [95% bootstrap CI] (n = questions it applies to)`.",
        "",
        md_table(headers, rows),
        "",
    ]
    if len({r.config.questions_sha256 for r in runs}) > 1:
        out += [
            "> **Warning:** these runs used different question files (sha256 differs). "
            "Their numbers are not directly comparable.",
            "",
        ]
    return out


def _metric_table(runs: list[LoadedRun], keys: list[str], k: int | str) -> str:
    keys = [key for key in keys if _has_data(runs, key)]
    headers = ["Run"] + [METRICS_BY_KEY[key].title(k) for key in keys]
    rows = [[r.name] + [fmt_stat(r.summary["overall"][key]) for key in keys] for r in runs]
    return md_table(headers, rows)


def _main_table(runs: list[LoadedRun], k: int | str) -> str:
    keys = [key for key in MAIN_METRICS if _has_data(runs, key) or key != "correctness"]
    headers = ["Run"] + [METRICS_BY_KEY[key].title(k) for key in keys]
    headers += ["p50 latency (ms)", "p95 latency (ms)"]
    rows = []
    for r in runs:
        latency = r.summary["latency_ms"]
        row = [r.name] + [fmt_stat(r.summary["overall"][key]) for key in keys]
        rows.append(row + [_fmt_num(latency["p50"], 0), _fmt_num(latency["p95"], 0)])
    return md_table(headers, rows)


def _per_qtype_tables(runs: list[LoadedRun], k: int | str) -> list[str]:
    qtypes = sorted({qt for r in runs for qt in r.summary["per_qtype"]})
    out: list[str] = []
    for key in MAIN_METRICS:
        if not _has_data(runs, key):
            continue
        out += [f"### {METRICS_BY_KEY[key].title(k)} by qtype", ""]
        rows = []
        for qt in qtypes:
            cells = [qt]
            for r in runs:
                block = r.summary["per_qtype"].get(qt)
                cells.append(fmt_stat(block["metrics"][key]) if block else DASH)
            rows.append(cells)
        out += [md_table(["qtype"] + [r.name for r in runs], rows), ""]
    return out


def _sort_key(r: QuestionResult) -> tuple[float, float, str]:
    recall = 1.0 if r.recall is None else r.recall
    grounded = 1.0 if r.groundedness is None else r.groundedness
    return (recall, grounded, r.question_id)


def worst_questions(results: list[QuestionResult], n: int = N_FAILURES) -> list[QuestionResult]:
    """Lowest recall first, then lowest groundedness. Questions with neither are skipped."""
    scored = [r for r in results if r.recall is not None or r.groundedness is not None]
    return sorted(scored, key=_sort_key)[:n]


def _ids(ids: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in ids) if ids else DASH


def _failure_log(run: LoadedRun, gold: dict[str, EvalQuestion]) -> list[str]:
    out = [f"### {run.name}", ""]
    rows = []
    for r in worst_questions(run.results):
        q = gold.get(r.question_id)
        gold_ids = q.gold_ids if q else None
        missed = [g for g in gold_ids if g not in r.retrieved_ids] if gold_ids else []
        rows.append(
            [
                r.question_id,
                r.qtype,
                _fmt_num(r.recall),
                _fmt_num(r.groundedness),
                _ids(r.retrieved_ids),
                _ids(gold_ids) if gold_ids is not None else "(questions file not found)",
                _ids(missed),
            ]
        )
    headers = ["Question", "qtype", "Recall", "Groundedness", "Retrieved", "Gold", "Missed gold"]
    out += [md_table(headers, rows) if rows else "_No scored questions._", ""]
    errors = [r for r in run.results if r.error]
    if errors:
        out += [f"Errors ({len(errors)}):", ""]
        out += [f"- `{r.question_id}`: {_cell(r.error)}" for r in errors] + [""]
    return out


def _load_gold(run: LoadedRun, questions_path: str | Path | None) -> dict[str, EvalQuestion]:
    path = Path(questions_path or run.config.questions_path)
    if not path.is_file():
        logger.warning("questions file %s not found; failure log will omit gold IDs", path)
        return {}
    return {q.id: q for q in load_questions(path)}


def _charts(runs: list[LoadedRun], out_path: Path, k: int | str) -> dict[str, str]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    charts: dict[str, str] = {}
    names = [r.name for r in runs]
    hits = [r.summary["overall"]["hit"] for r in runs]
    if any(h["n"] for h in hits):
        means = [h["mean"] or 0.0 for h in hits]
        err = [
            [(h["mean"] - h["low"]) if h["n"] else 0 for h in hits],
            [(h["high"] - h["mean"]) if h["n"] else 0 for h in hits],
        ]
        fig, ax = plt.subplots(figsize=(max(4, 1.4 * len(runs)), 3.2))
        ax.bar(names, means, yerr=err, capsize=4, color="#4C72B0")
        ax.set_ylim(0, 1.05)
        ax.set_ylabel(f"Hit@{k}")
        ax.set_title(f"Hit@{k} by run (95% CI)")
        fig.tight_layout()
        path = out_path.with_name(f"{out_path.stem}_hit_by_run.png")
        fig.savefig(path, dpi=120)
        plt.close(fig)
        charts["hit"] = path.name
    if _has_data(runs, "groundedness"):
        charts["groundedness"] = _groundedness_chart(runs, out_path, plt)
    return charts


def _groundedness_chart(runs: list[LoadedRun], out_path: Path, plt: Any) -> str:
    qtypes = sorted({qt for r in runs for qt in r.summary["per_qtype"]})
    width = 0.8 / len(runs)
    fig, ax = plt.subplots(figsize=(max(5, 1.2 * len(qtypes)), 3.2))
    for i, r in enumerate(runs):
        values = []
        for qt in qtypes:
            block = r.summary["per_qtype"].get(qt)
            mean = block["metrics"]["groundedness"]["mean"] if block else None
            values.append(mean or 0.0)
        ax.bar([x + i * width for x in range(len(qtypes))], values, width, label=r.name)
    ax.set_xticks([x + width * (len(runs) - 1) / 2 for x in range(len(qtypes))], qtypes)
    ax.set_ylim(0, 1.05)
    ax.set_ylabel("Groundedness")
    ax.set_title("Groundedness by qtype")
    ax.legend(fontsize="small")
    fig.tight_layout()
    path = out_path.with_name(f"{out_path.stem}_groundedness_by_qtype.png")
    fig.savefig(path, dpi=120)
    plt.close(fig)
    return path.name


def render_report(
    runs: list[LoadedRun],
    charts: dict[str, str] | None = None,
    questions_path: str | Path | None = None,
) -> str:
    if not runs:
        raise ValueError("no runs to report")
    k = _k_label(runs)
    charts = charts or {}
    lines = _header(runs)
    lines += ["## Main results", "", _main_table(runs, k), ""]
    if any(_has_data(runs, key) for key in DIAGNOSTIC_METRICS):
        lines += ["## Diagnostics", "", _metric_table(runs, DIAGNOSTIC_METRICS, k), ""]
    if not _has_data(runs, "groundedness"):
        lines += ["_No answer metrics: these runs were retrieval-only._", ""]
    lines += ["## Charts", ""]
    if "hit" in charts:
        lines += [f"![Hit@{k} by run]({charts['hit']})", ""]
    if "groundedness" in charts:
        lines += [f"![Groundedness by qtype]({charts['groundedness']})", ""]
    lines += ["## Per-qtype results", ""] + _per_qtype_tables(runs, k)
    lines += [
        f"## Failure log ({N_FAILURES} worst questions per run)",
        "",
        "Sorted by lowest recall, then lowest groundedness.",
        "",
    ]
    for run in runs:
        lines += _failure_log(run, _load_gold(run, questions_path))
    return "\n".join(lines).rstrip() + "\n"


def write_report(
    runs: list[LoadedRun], out_path: str | Path, questions_path: str | Path | None = None
) -> Path:
    """Write the markdown report and its PNG charts (next to the report)."""
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    charts = _charts(runs, out, _k_label(runs))
    out.write_text(render_report(runs, charts, questions_path), encoding="utf-8", newline="\n")
    return out


# --- compare -----------------------------------------------------------------------------


def paired_metric(
    a: list[QuestionResult],
    b: list[QuestionResult],
    spec: MetricSpec,
    n_resamples: int = 2000,
    seed: int = 0,
) -> dict[str, Any] | None:
    """Paired bootstrap of B - A over questions where the metric applies in BOTH runs."""
    b_by_id = {r.question_id: r for r in b}
    pairs = []
    for ra in a:
        rb = b_by_id.get(ra.question_id)
        va = spec.extract(ra)
        vb = spec.extract(rb) if rb is not None else None
        if va is not None and vb is not None:
            pairs.append((va, vb))
    if not pairs:
        return None
    a_vals, b_vals = [p[0] for p in pairs], [p[1] for p in pairs]
    diff, low, high = paired_bootstrap(a_vals, b_vals, n_resamples=n_resamples, seed=seed)
    return {
        "diff": diff,
        "low": low,
        "high": high,
        "n": len(pairs),
        "mean_a": sum(a_vals) / len(a_vals),
        "mean_b": sum(b_vals) / len(b_vals),
    }


def compare_runs(
    a: LoadedRun, b: LoadedRun, n_resamples: int = 2000, seed: int = 0
) -> dict[str, Any]:
    """Paired differences (B - A) for every metric, overall and per qtype."""
    if a.config.questions_sha256 != b.config.questions_sha256:
        raise CompareError(
            f"runs used different question files: {a.name} has questions_sha256 "
            f"{_short(a.config.questions_sha256)}…, {b.name} has "
            f"{_short(b.config.questions_sha256)}…. Re-run both on the same frozen "
            "benchmark before comparing."
        )
    specs = [METRICS_BY_KEY[key] for key in COMPARE_METRICS]
    overall = {s.key: paired_metric(a.results, b.results, s, n_resamples, seed) for s in specs}
    per_qtype: dict[str, dict[str, Any]] = {}
    for qt in sorted({r.qtype for r in a.results}):
        a_sub = [r for r in a.results if r.qtype == qt]
        per_qtype[qt] = {
            s.key: paired_metric(a_sub, b.results, s, n_resamples, seed) for s in specs
        }
    return {"a": a.name, "b": b.name, "overall": overall, "per_qtype": per_qtype}


def _pts(x: float) -> str:
    return f"{x * 100:+.1f}"


def describe_difference(label: str, stat: dict[str, Any], spec: MetricSpec) -> str:
    """One plain-language line, e.g. ``Hit@5 +12.5 pts [95% CI +2.5, +22.5] (n=40): ...``."""
    text = (
        f"{label} {_pts(stat['diff'])} pts [95% CI {_pts(stat['low'])}, {_pts(stat['high'])}] "
        f"(n={stat['n']})"
    )
    if stat["low"] <= 0 <= stat["high"]:
        return f"{text}: the CI includes zero, so the difference is not clear at this sample size."
    direction = "higher" if stat["diff"] > 0 else "lower"
    note = "" if spec.higher_is_better else " (lower is better for this metric)"
    return f"{text}: B is clearly {direction} than A{note}."


def _metric_label(spec: MetricSpec, a: LoadedRun, b: LoadedRun) -> str:
    if a.config.k == b.config.k:
        return spec.title(a.config.k)
    return spec.title("k") + f" (A k={a.config.k}, B k={b.config.k})"


def render_compare(a: LoadedRun, b: LoadedRun, comparison: dict[str, Any]) -> str:
    lines = [
        f"# Comparison: B = {b.name} vs A = {a.name}",
        "",
        "Differences are B − A in percentage points with a paired bootstrap 95% CI, "
        "computed over questions scored in both runs. A CI that includes zero means the "
        "difference is not clear at this sample size.",
        "",
        "## Overall",
        "",
    ]
    for key, stat in comparison["overall"].items():
        if stat is not None:
            spec = METRICS_BY_KEY[key]
            lines.append(f"- {describe_difference(_metric_label(spec, a, b), stat, spec)}")
    for qt, block in comparison["per_qtype"].items():
        entries = [(key, stat) for key, stat in block.items() if stat is not None]
        if not entries:
            continue
        lines += ["", f"## qtype `{qt}`", ""]
        for key, stat in entries:
            spec = METRICS_BY_KEY[key]
            lines.append(f"- {describe_difference(_metric_label(spec, a, b), stat, spec)}")
    return "\n".join(lines) + "\n"
